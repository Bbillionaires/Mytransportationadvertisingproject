/** Android hardware key attestation at enrollment (R-028). Chains are SYNTHETIC (test root); see attestationChain.ts. */
import { createPublicKey, generateKeyPairSync, randomBytes, X509Certificate } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { parseDer } from '../src/lib/der.js';
import { googleAttestationTrust, normalizeSerial, parseStatusList, verifyAttestation, type AttestationTrust } from '../src/modules/devices/attestation.js';
import { GOOGLE_ATTESTATION_ROOTS_PEM } from '../src/modules/devices/googleAttestationRoots.js';
import { TestAttestationCa } from './attestationChain.js';
import { FakeTablet, org, setupApp, userWithRole, type Ctx } from './helpers.js';

const ca = new TestAttestationCa();
const challenge = randomBytes(32);
const check = (a: ReturnType<TestAttestationCa['attest']>, over: { challenge?: Buffer; trust?: AttestationTrust; publicKeyB64?: string } = {}) =>
  verifyAttestation({ chainB64: a.chain, publicKeyDer: Buffer.from(over.publicKeyB64 ?? a.publicKeyB64, 'base64'), challenge: over.challenge ?? challenge, trust: over.trust ?? ca.trust() });

describe('attestation chain verification', () => {
  it('accepts a TEE or StrongBox key generated by our app on a verified, locked device', async () => {
    expect(await check(ca.attest({ challenge }))).toMatchObject({ securityLevel: 'TRUSTED_ENVIRONMENT', bootState: 'VERIFIED', deviceLocked: true, revocationChecked: true });
    expect((await check(ca.attest({ challenge, securityLevel: 2 }))).securityLevel).toBe('STRONGBOX');
  });

  it('reports an unlocked bootloader or unverified boot instead of hiding it', async () => {
    expect(await check(ca.attest({ challenge, deviceLocked: false, bootState: 2 }))).toMatchObject({ bootState: 'UNVERIFIED', deviceLocked: false });
  });

  it.each([
    ['a different challenge (replay)', { challenge: randomBytes(32) }, {}, /challenge does not match/],
    ['a software-only key', { challenge, securityLevel: 0 }, {}, /not hardware-backed/],
    ['an imported key', { challenge, origin: 2 }, {}, /imported/],
    ['another app’s key', { challenge, packageName: 'com.example.attacker' }, {}, /another app/],
    ['no root of trust', { challenge, omitRootOfTrust: true }, {}, /root of trust/],
  ] as const)('rejects %s', async (_n, kd, _o, err) => {
    await expect(check(ca.attest(kd))).rejects.toThrow(err);
  });

  it('rejects a chain for a key other than the one being enrolled', async () => {
    const other = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
    await expect(check(ca.attest({ challenge }, { attestedKey: other.publicKey }))).rejects.toThrow(/does not match the enrolled public key/);
  });

  it('rejects chains that do not end in a trusted root, or are broken, expired or revoked', async () => {
    const a = ca.attest({ challenge });
    await expect(check(a, { trust: new TestAttestationCa().trust() })).rejects.toThrow(/trusted Google attestation root/);
    const other = new TestAttestationCa().attest({ challenge });
    await expect(check({ ...a, chain: [a.chain[0]!, other.chain[1]!, other.chain[2]!] })).rejects.toThrow(/not signed by/);
    await expect(check({ ...a, chain: [a.chain[0]!, a.chain[2]!] })).rejects.toThrow(/not signed by/);
    await expect(check({ ...a, chain: [a.chain[0]!] })).rejects.toThrow(/2 to 10/);

    const expired = new TestAttestationCa({ intermediateNotAfter: new Date(Date.now() - 1000) });
    await expect(check(expired.attest({ challenge }), { trust: expired.trust() })).rejects.toThrow(/expired/);

    const revoking = new TestAttestationCa();
    revoking.revoked.add(normalizeSerial(new X509Certificate(revoking.intermediateCert).serialNumber));
    await expect(check(revoking.attest({ challenge }), { trust: revoking.trust() })).rejects.toThrow(/revoked/);
  });

  it('still verifies when Google’s revocation list is unreachable, and says so', async () => {
    const r = await check(ca.attest({ challenge }), { trust: { ...ca.trust(), revokedSerials: async () => null } });
    expect(r.revocationChecked).toBe(false);
  });

  it('survives corrupted input without crashing (only AttestationError or a clean rejection)', async () => {
    const a = ca.attest({ challenge });
    const leaf = Buffer.from(a.chain[0]!, 'base64');
    for (let i = 0; i < 300; i++) {
      const bad = Buffer.from(leaf);
      const at = Math.floor(Math.random() * bad.length);
      bad[at] = bad[at]! ^ (1 << Math.floor(Math.random() * 8));
      await check({ ...a, chain: [bad.toString('base64'), a.chain[1]!, a.chain[2]!] }).then(() => undefined, (e) => expect(e).toBeInstanceOf(Error));
    }
    expect(() => parseDer(Buffer.from([0x30, 0x80, 0, 0]))).toThrow(/indefinite/);
    expect(() => parseDer(Buffer.from([0x04, 0x81, 0x05, 1, 2, 3, 4, 5]))).toThrow(/non-minimal/);
    expect(() => parseDer(Buffer.from([0x04, 0x05, 1]))).toThrow(/truncated/);
  });
});

describe('a real Android attestation chain (Google sample, rooted in a pinned Google root)', () => {
  const fx = JSON.parse(readFileSync(new URL('./fixtures/google-sample-ec-tee-chain.json', import.meta.url), 'utf8')) as { chain: string[] };
  const leaf = new X509Certificate(Buffer.from(fx.chain[0]!, 'base64'));
  const run = (over: { challenge?: Buffer; packageName?: string; now?: Date } = {}) => verifyAttestation({
    chainB64: fx.chain, publicKeyDer: leaf.publicKey.export({ type: 'spki', format: 'der' }) as Buffer, challenge: over.challenge ?? Buffer.from('abc'),
    trust: googleAttestationTrust(async () => null), packageName: over.packageName ?? 'android', now: over.now ?? new Date('2018-04-01T00:00:00Z') });

  it('verifies end to end against Google’s real root and reports the unlocked developer bootloader', async () => {
    expect(await run()).toMatchObject({ securityLevel: 'TRUSTED_ENVIRONMENT', attestationVersion: 3, bootState: 'UNVERIFIED', deviceLocked: false });
  });
  it('still enforces challenge, package and the intermediates’ validity on real data', async () => {
    await expect(run({ challenge: Buffer.from('abd') })).rejects.toThrow(/challenge/);
    await expect(run({ packageName: 'net.ridesharemedia.shell' })).rejects.toThrow(/another app/);
    await expect(run({ now: new Date('2040-01-01T00:00:00Z') })).rejects.toThrow(/expired/);
  });
});

describe('pinned Google roots and revocation list', () => {
  it('pins Google’s two published attestation roots', () => {
    const roots = GOOGLE_ATTESTATION_ROOTS_PEM.map((p) => new X509Certificate(p));
    expect(roots).toHaveLength(2);
    for (const r of roots) expect(r.verify(r.publicKey)).toBe(true);
    expect(roots.map((r) => r.publicKey.asymmetricKeyType).sort()).toEqual(['ec', 'rsa']);
    expect(googleAttestationTrust(async () => null).rootsSpki).toHaveLength(2);
  });

  it('reads Google’s status list format; serials compare without case or leading zeros', () => {
    const s = parseStatusList({ entries: { '0Ab12': { status: 'REVOKED', reason: 'KEY_COMPROMISE' }, c0ffee: { status: 'SUSPENDED' }, '77': { status: 'OK' } } });
    expect([...s].sort()).toEqual(['ab12', 'c0ffee']);
    expect(() => parseStatusList({})).toThrow();
    expect(normalizeSerial('00FF')).toBe('ff');
    expect(normalizeSerial('0')).toBe('0');
  });
});

describe('enrollment with attestation', () => {
  let ctx: Ctx, strict: Ctx, orgId: string, admin: Awaited<ReturnType<typeof userWithRole>>, strictAdmin: typeof admin;
  beforeAll(async () => {
    ctx = await setupApp({ attestationTrust: ca.trust() });
    strict = await setupApp({ attestationTrust: ca.trust(), env: { DEVICE_ATTESTATION: 'required' } });
    orgId = await org(ctx.db, 'FLEET_OPERATOR');
    admin = await userWithRole(ctx, orgId, 'fleet_admin');
    strictAdmin = await userWithRole(strict, orgId, 'fleet_admin');
  });
  afterAll(async () => { for (const c of [ctx, strict]) { await c.app.close(); await c.db.end(); } });

  const newCode = async (c: Ctx, h: Record<string, string>) => (await c.app.inject({ method: 'POST', url: `/v1/orgs/${orgId}/devices/enrollment-codes`, headers: h, payload: {} })).json().code as string;
  const getChallenge = async (c: Ctx, code: string) => {
    const r = await c.app.inject({ method: 'POST', url: '/v1/devices/enroll/challenge', payload: { code } });
    expect(r.statusCode, r.body).toBe(200);
    return Buffer.from(r.json().challenge, 'base64');
  };
  const enroll = (c: Ctx, t: FakeTablet, code: string, chain?: string[]) => c.app.inject({ method: 'POST', url: '/v1/devices/enroll',
    payload: { code, serial: t.serial, publicKey: t.publicKeyB64, appVersion: '1.0+android-1.0', ...(chain ? { attestation: { chain } } : {}) } });
  const attestFor = (t: FakeTablet, ch: Buffer, over: Parameters<TestAttestationCa['attest']>[0] extends infer K ? Partial<K> : never = {}) =>
    ca.attest({ challenge: ch, ...over }, { devicePublicKey: createPublicKey({ key: Buffer.from(t.publicKeyB64, 'base64'), format: 'der', type: 'spki' }) }).chain;

  it('records a verified hardware key; the fleet sees it; the tablet works normally', async () => {
    const code = await newCode(ctx, admin.h);
    const t = new FakeTablet(ctx.app, undefined, 'p256');
    const r = await enroll(ctx, t, code, attestFor(t, await getChallenge(ctx, code), { securityLevel: 2 }));
    expect(r.statusCode, r.body).toBe(201);
    expect(r.json().attestation).toBe('VERIFIED');
    t.deviceId = r.json().deviceId;
    expect((await t.call('POST', '/v1/devices/heartbeat', { appVersion: '1.0' })).statusCode).toBe(200);
    const d = (await ctx.app.inject({ method: 'GET', url: `/v1/orgs/${orgId}/devices`, headers: admin.h })).json().items.find((x: any) => x.id === t.deviceId);
    expect(d).toMatchObject({ attestation_status: 'VERIFIED', attestation_security_level: 'STRONGBOX', attestation_boot_state: 'VERIFIED', keyType: 'ECDSA_P256' });
    const a = await ctx.db.query(`SELECT details FROM audit_log WHERE action = 'device.enrolled' AND target_id = $1`, [t.deviceId]);
    expect(a.rows[0].details).toMatchObject({ attestation: 'VERIFIED', securityLevel: 'STRONGBOX' });
  });

  it('optional mode: web players still enroll (NONE); a bad chain is recorded as FAILED with the reason', async () => {
    const web = new FakeTablet(ctx.app);
    const r1 = await enroll(ctx, web, await newCode(ctx, admin.h));
    expect(r1.json().attestation).toBe('NONE');

    // A chain made for another code's challenge cannot be replayed.
    const codeA = await newCode(ctx, admin.h), codeB = await newCode(ctx, admin.h);
    const t = new FakeTablet(ctx.app, undefined, 'p256');
    const chain = attestFor(t, await getChallenge(ctx, codeA));
    await getChallenge(ctx, codeB);
    const r2 = await enroll(ctx, t, codeB, chain);
    expect(r2.statusCode).toBe(201);
    expect(r2.json().attestation).toBe('FAILED');
    const row = (await ctx.db.query('SELECT attestation_failure FROM devices WHERE id = $1', [r2.json().deviceId])).rows[0];
    expect(row.attestation_failure).toMatch(/challenge does not match/);

    // Sending a chain without first asking for a challenge also fails verification.
    const t3 = new FakeTablet(ctx.app, undefined, 'p256');
    const r3 = await enroll(ctx, t3, await newCode(ctx, admin.h), attestFor(t3, randomBytes(32)));
    expect(r3.json().attestation).toBe('FAILED');
  });

  it('the challenge endpoint refuses unknown or used codes', async () => {
    expect((await ctx.app.inject({ method: 'POST', url: '/v1/devices/enroll/challenge', payload: { code: 'NOT-A-REAL-CODE-123' } })).statusCode).toBe(401);
  });

  it('required mode: refuses web players, failed chains and unlocked bootloaders; accepts verified hardware', async () => {
    const web = new FakeTablet(strict.app);
    const r1 = await enroll(strict, web, await newCode(strict, strictAdmin.h));
    expect(r1.statusCode).toBe(403);
    expect(r1.json().error.message).toMatch(/prove a hardware key/);

    const code = await newCode(strict, strictAdmin.h);
    const rooted = new FakeTablet(strict.app, undefined, 'p256');
    const r2 = await enroll(strict, rooted, code, attestFor(rooted, await getChallenge(strict, code), { deviceLocked: false, bootState: 2 }));
    expect(r2.statusCode).toBe(403);
    expect(r2.json().error.message).toMatch(/bootloader is unlocked/);

    // The refusal left the code unused; a fresh challenge and a good tablet succeed.
    const good = new FakeTablet(strict.app, undefined, 'p256');
    const r3 = await enroll(strict, good, code, attestFor(good, await getChallenge(strict, code)));
    expect(r3.statusCode, r3.body).toBe(201);
    expect(r3.json().attestation).toBe('VERIFIED');
  });
});


describe('per-fleet "verified tablets only" (D-059)', () => {
  let ctx: Ctx, orgId: string, otherOrg: string, admin: Awaited<ReturnType<typeof userWithRole>>, viewer: typeof admin, otherAdmin: typeof admin;
  beforeAll(async () => {
    ctx = await setupApp({ attestationTrust: ca.trust() });
    orgId = await org(ctx.db, 'FLEET_OPERATOR');
    otherOrg = await org(ctx.db, 'FLEET_OPERATOR');
    admin = await userWithRole(ctx, orgId, 'fleet_admin');
    viewer = await userWithRole(ctx, orgId, 'fleet_viewer');
    otherAdmin = await userWithRole(ctx, otherOrg, 'fleet_admin');
  });
  afterAll(async () => { await ctx.app.close(); await ctx.db.end(); });

  const api = (method: 'GET' | 'PUT' | 'POST', url: string, h: Record<string, string>, payload?: object) => ctx.app.inject({ method, url, headers: h, ...(payload ? { payload } : {}) });
  const code = async (o = orgId, h = admin.h) => (await api('POST', `/v1/orgs/${o}/devices/enrollment-codes`, h, {})).json().code as string;
  const enrollWeb = async (c: string) => { const t = new FakeTablet(ctx.app); return ctx.app.inject({ method: 'POST', url: '/v1/devices/enroll', payload: { code: c, serial: t.serial, publicKey: t.publicKeyB64, appVersion: '1' } }); };

  it('a fleet admin turns it on; web players are then refused for that fleet only; existing tablets are counted, not cut off', async () => {
    expect((await enrollWeb(await code())).statusCode).toBe(201);
    expect((await api('PUT', `/v1/orgs/${orgId}/devices/policy`, viewer.h, { requireHardwareAttestation: true })).statusCode).toBe(403);
    expect((await api('PUT', `/v1/orgs/${orgId}/devices/policy`, admin.h, { requireHardwareAttestation: true })).statusCode).toBe(200);
    expect((await api('GET', `/v1/orgs/${orgId}/devices/policy`, viewer.h)).json()).toEqual({ requireHardwareAttestation: true, networkMode: 'optional', unverifiedTablets: 1 });

    const refused = await enrollWeb(await code());
    expect(refused.statusCode).toBe(403);
    expect(refused.json().error).toMatchObject({ code: 'HARDWARE_ATTESTATION_REQUIRED', message: expect.stringMatching(/This fleet only accepts/) });
    expect((await enrollWeb(await code(otherOrg, otherAdmin.h))).statusCode).toBe(201);

    const c = await code();
    const t = new FakeTablet(ctx.app, undefined, 'p256');
    const ch = Buffer.from((await ctx.app.inject({ method: 'POST', url: '/v1/devices/enroll/challenge', payload: { code: c } })).json().challenge, 'base64');
    const chain = ca.attest({ challenge: ch }, { devicePublicKey: createPublicKey({ key: Buffer.from(t.publicKeyB64, 'base64'), format: 'der', type: 'spki' }) }).chain;
    const ok = await ctx.app.inject({ method: 'POST', url: '/v1/devices/enroll', payload: { code: c, serial: t.serial, publicKey: t.publicKeyB64, appVersion: '1', attestation: { chain } } });
    expect(ok.statusCode, ok.body).toBe(201);

    expect((await api('PUT', `/v1/orgs/${orgId}/devices/policy`, otherAdmin.h, { requireHardwareAttestation: false })).statusCode).toBe(403);
    const a = await ctx.db.query(`SELECT count(*)::int AS n FROM audit_log WHERE action = 'device.policy_changed' AND org_id = $1`, [orgId]);
    expect(a.rows[0].n).toBe(1);
  });
});
